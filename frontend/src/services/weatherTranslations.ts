    default:
      return `Current temperature is ${roundedTemp} degrees Celsius. ${conditionText}. ${
        safeSpray ? 'Safe to spray chemicals today.' : 'Delay chemical spray today.'
      } ${isRain ? 'Postpone irrigation due to expected rain.' : 'Normal irrigation recommended.'}`
