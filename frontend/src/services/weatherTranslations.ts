export function getLocalizedCondition(lang: string, code?: number, fallbackText?: string): string {
  if (code !== undefined) {
    const dict = CONDITIONS_BY_LANG[lang] || CONDITIONS_BY_LANG.en
    if (dict && dict[code]) {
      return dict[code]
    }
  }
  return fallbackText || (CONDITIONS_BY_LANG[lang]?.[0] || 'Clear sky')
}

