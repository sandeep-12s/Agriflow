export function translate(language: Language, key: TranslationKey): string {
  const dict = (translations as Record<string, Record<string, string>>)[language]
  if (dict && dict[key]) {
    return dict[key]
  }
  if (language === 'en') {
    return (translations.en as Record<string, string>)[key] || ''
  }
  if (['hi', 'mai', 'ks', 'ne'].includes(language)) {
    return (translations.hi as Record<string, string>)[key] || (translations.en as Record<string, string>)[key] || ''
  }
  // For regional languages (pa, mr, gu, te, ta, bn, kn, ml, or, ur, as, kok)
  // fallback to English if key is missing, so users never see unexpected Hindi
  return (translations.en as Record<string, string>)[key] || (translations.hi as Record<string, string>)[key] || ''
}

